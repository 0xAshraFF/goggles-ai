"""Build goggles_ai/utils/confusables_ascii.txt from Unicode's confusables.txt (UTS #39).

Keeps only single-codepoint letters that look like a single ASCII letter, and
drops sources that legitimately appear in Latin-script text:
  - anything named LATIN... (ligatures like U+FB01, dotless i, IPA, small caps)
  - modifier letters (category Lm) and non-letters (punctuation, digits, symbols)
Fullwidth Latin and mathematical alphanumerics are kept, since they are not
used in ordinary prose.

Usage:
    python tools/build_confusables.py
"""

from __future__ import annotations

import unicodedata
import urllib.request
from pathlib import Path

SOURCE_URL = "https://www.unicode.org/Public/security/latest/confusables.txt"
OUT = Path(__file__).resolve().parent.parent / "goggles_ai" / "utils" / "confusables_ascii.txt"

HEADER = """\
# ASCII-target subset of Unicode confusables.txt (UTS #39), generated by
# tools/build_confusables.py. Source: {url}
# Source {version}
#
# Format: <source codepoint> ; <ASCII letter codepoint> ; # <source name>
#
# Unicode data (c) Unicode, Inc. Terms of use: https://www.unicode.org/terms_of_use.html
# License: Unicode License v3, https://www.unicode.org/license.txt
"""


def keep(src: str) -> bool:
    if ord(src) < 128 or unicodedata.category(src) not in ("Lu", "Ll", "Lo", "Lt"):
        return False
    return not unicodedata.name(src, "LATIN").startswith("LATIN")


def main() -> None:
    req = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "goggles-ai-build"})
    text = urllib.request.urlopen(req, timeout=60).read().decode("utf-8-sig")
    version = next((ln.lstrip("# ").strip() for ln in text.splitlines()[:5] if ln.startswith("# Date:")), "unknown")

    rows: dict[str, str] = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        src, dst, *_ = [p.strip() for p in line.split(";")]
        if len(src.split()) != 1 or len(dst.split()) != 1:
            continue
        s, d = chr(int(src, 16)), chr(int(dst, 16))
        if ("a" <= d <= "z" or "A" <= d <= "Z") and keep(s):
            rows[s] = d

    lines = [HEADER.format(url=SOURCE_URL, version=version)]
    for s, d in sorted(rows.items(), key=lambda kv: ord(kv[0])):
        lines.append(f"{ord(s):04X} ;\t{ord(d):04X} ;\t# {unicodedata.name(s, '?')}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} mappings to {OUT}")


if __name__ == "__main__":
    main()
